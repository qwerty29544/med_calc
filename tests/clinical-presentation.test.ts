import { describe, expect, it } from 'vitest';
import { recommendationText } from '../apps/web/components/clinical-text';

describe('представление рекомендации', () => {
  it('убирает общие демо-строки, сохраняя конкретные ограничения и версии', () => {
    const text = [
      'Демонстрационный расчет. Медицинский пакет не утвержден.',
      'Нозология: Острый бронхит',
      'Внимание: Препарат исключён: конкретное противопоказание.',
      'Внимание: Демонстрационный расчет: медицинский пакет DRAFT не утвержден для клинического применения.',
      'Версии: clinical_rules 0.1.0',
    ].join('\n');
    expect(recommendationText(text, true)).toBe(
      'Нозология: Острый бронхит\nВнимание: Препарат исключён: конкретное противопоказание.\nВерсии: clinical_rules 0.1.0',
    );
    expect(text).toContain('Медицинский пакет не утвержден.');
  });

  it('сохраняет сообщения утверждённого результата и не удаляет строки по подстроке', () => {
    expect(
      recommendationText('Результат поддержки врачебного решения.\nКонкретное предупреждение DRAFT', false),
    ).toBe('Результат поддержки врачебного решения.\nКонкретное предупреждение DRAFT');
    expect(recommendationText('Непереносимость препарата: 2 разf', true)).toBe(
      'Непереносимость препарата: 2 раза',
    );
  });
});
